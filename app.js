const translatable = [
  ['[data-i18n]', 'i18n', 'textContent'],
  ['[data-placeholder]', 'placeholder', 'placeholder'],
  ['[data-aria]', 'aria', 'ariaLabel'],
  ['[data-alt]', 'alt', 'alt'],
].flatMap(([selector, key, property]) => Array.from(document.querySelectorAll(selector), element => ({
  element, property, fa: element[property], en: english[element.dataset[key]],
})));
const languageButtons = document.querySelectorAll('[data-lang]');
const page = document.querySelector('[data-page]')?.dataset;
const metaDescription = document.querySelector('meta[name="description"]');
const originalTitle = document.title;
const originalDescription = metaDescription?.content;
const localizedTitle = {
  journal: 'Insights | Atiyeh Kiaee',
  missing: 'Insight not found | Atiyeh Kiaee',
};
const article = document.getElementById('post-article');
const persianArticle = article?.cloneNode(true);
const englishArticle = document.getElementById('post-english');

function setArticleLanguage(isEnglish) {
  if (article.dataset.language === (isEnglish ? 'en' : 'fa')) return;
  const edition = isEnglish ? englishArticle.content : persianArticle;
  article.replaceChildren(...Array.from(edition.childNodes, node => node.cloneNode(true)));
  article.dataset.language = isEnglish ? 'en' : 'fa';
}
if (article) {
  article.dataset.language = 'fa';
  article.addEventListener('click', event => {
    if (!event.target.closest('[data-read-persian]')) return;
    setLanguage('fa');
    article.querySelector('h1').setAttribute('tabindex', '-1');
    article.querySelector('h1').focus();
  });
}

function setLanguage(language) {
  const isEnglish = language === 'en';
  document.documentElement.lang = language;
  document.documentElement.dir = isEnglish ? 'ltr' : 'rtl';
  document.querySelector('link[rel="icon"]').href = isEnglish ? '/Personal-Brand/assets/favicon.svg' : '/Personal-Brand/assets/favicon-fa.svg';
  for (const {element, property, fa, en} of translatable) element[property] = isEnglish ? (en ?? fa) : fa;
  for (const button of languageButtons) button.setAttribute('aria-pressed', String(button.dataset.lang === language));
  if (article) setArticleLanguage(isEnglish);
  const pageType = page?.page;
  const englishTitle = article ? page.titleEn + ' | Atiyeh Kiaee' : localizedTitle[pageType] ?? 'Atiyeh Kiaee | Business Strategy & Operations Advisor';
  document.title = isEnglish ? englishTitle : originalTitle;
  if (metaDescription) metaDescription.content = isEnglish
    ? (article ? page.descriptionEn : pageType === 'journal' ? english.journalIntro : english.heroDescription)
    : originalDescription;
  try { localStorage.setItem('atie-language', language); } catch { /* The preference is optional. */ }
  document.dispatchEvent(new CustomEvent('atie-language-change'));
}

for (const button of languageButtons) button.addEventListener('click', () => setLanguage(button.dataset.lang));
let preferredLanguage = 'fa';
try { if (localStorage.getItem('atie-language') === 'en') preferredLanguage = 'en'; } catch { /* Use Persian by default. */ }
setLanguage(preferredLanguage);

const menuToggle = document.querySelector('.menu-toggle');
const mobileNav = document.getElementById('mobile-nav');
function setMenu(open) {
  menuToggle.setAttribute('aria-expanded', String(open));
  mobileNav.hidden = !open;
}
menuToggle.addEventListener('click', () => setMenu(mobileNav.hidden));
mobileNav.addEventListener('click', event => {
  if (event.target.closest('a')) setMenu(false);
});
document.addEventListener('keydown', event => {
  if (event.key === 'Escape' && !mobileNav.hidden) {
    setMenu(false);
    menuToggle.focus();
  }
});
window.matchMedia('(min-width: 921px)').addEventListener('change', event => {
  if (event.matches) setMenu(false);
});
